// Runs INSIDE a Docker container with internet: installs the public site, imports the game ZIPs,
// waits for the offline cache, then waits for the host to cut the network (touch /sig/offline) and reloads.
import { createRequire } from "node:module";
import { existsSync, writeFileSync } from "node:fs";
const require = createRequire("/w/");
const { chromium } = require("@playwright/test");
const SITE = process.env.SITE ?? "https://openzh.pikilon.com/";
const log = (...a) => console.log(new Date().toISOString().slice(11, 19), ...a);
const browser = await chromium.launch({ args: ["--enable-unsafe-webgpu", "--enable-features=Vulkan", "--use-angle=swiftshader", "--use-webgpu-adapter=swiftshader", "--ignore-gpu-blocklist"] });
const context = await browser.newContext({ viewport: { width: 1280, height: 800 } });
const page = await context.newPage();
page.on("pageerror", (e) => log("pageerror", String(e).slice(0, 200)));
const state = () => page.evaluate(() => document.body.dataset.state);
await page.goto(SITE);
await page.waitForFunction(() => crossOriginIsolated, null, { timeout: 60_000 });
log("isolated, state", await state());
await page.waitForFunction(() => document.body.dataset.state === "no-assets", null, { timeout: 60_000 });
await page.locator("#zip-input").setInputFiles(["/zips/generals.zip", "/zips/zero-hour.zip"]);
log("zips given");
await page.waitForFunction(() => ["playing", "no-assets", "error"].includes(document.body.dataset.state ?? "") && document.querySelector("#status")?.textContent?.match(/Ready|failed/), null, { timeout: 15 * 60_000 });
log("after import: state", await state(), "status", await page.locator("#status").innerText());
await page.waitForTimeout(20_000);
log("state after 20s", await state(), "status", await page.locator("#status").innerText());
await page.screenshot({ path: "/sig/1-online.png" });
await page.locator("#menu-button").click();
await page.waitForFunction(() => /ready, the game opens offline/.test(document.querySelector("#menu-offline")?.textContent ?? ""), null, { timeout: 120_000 });
log("menu:", await page.locator("#menu-offline").innerText(), "|", await page.locator("#menu-stored").innerText());
await page.keyboard.press("Escape");
writeFileSync("/sig/ready", "1");
log("waiting for the host to cut the network");
while (!existsSync("/sig/offline")) await new Promise((r) => setTimeout(r, 500));
const net = await page.evaluate(() => fetch("https://openzh.pikilon.com/dist/main.js", { cache: "no-store" }).then((r) => r.status, (e) => "FAIL " + e.message).catch((e) => String(e)));
log("network now:", net);
await page.reload({ waitUntil: "load" });
await page.waitForFunction(() => crossOriginIsolated, null, { timeout: 60_000 });
await page.waitForTimeout(15_000);
log("offline reload: state", await state(), "| status", await page.locator("#status").innerText(), "| offline badge visible", await page.locator("#offline").isVisible(), "| coi", await page.evaluate(() => crossOriginIsolated));
await page.locator("#menu-button").click();
log("menu stored:", await page.locator("#menu-stored").innerText(), "|", await page.locator("#menu-offline").innerText());
await page.keyboard.press("Escape");
await page.screenshot({ path: "/sig/2-offline.png" });
await browser.close();
writeFileSync("/sig/done", "1");
